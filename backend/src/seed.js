async function seedDatabase() {
  console.log("=================================");
  console.log("JobOne Development Seed Starting");
  console.log("=================================");

  try {
    await mongoose.connect(mongoUrl);
    console.log("Connected to MongoDB successfully.");

    // 1. Maintain baseline core accounts
    await createSeedAccount(
      Admin,
      process.env.SEED_ADMIN_EMAIL || "seed.admin@jobone.test",
      "Seed Admin",
      { role: "superAdmin" },
    );
    await createSeedAccount(
      Employer,
      process.env.SEED_EMPLOYER_EMAIL || "seed.employer@jobone.test",
      "Seed Employer",
      { companyName: "JobOne Test Company", isVerified: true, isApproved: "approved" },
      true,
    );
    await createSeedAccount(
      User,
      process.env.SEED_JOBSEEKER_EMAIL || "seed.jobseeker@jobone.test",
      "Seed Job Seeker",
      { isVerified: true },
      true,
    );

    // 2. Duplicate-safe Upsert for 8 Realistic Company Employers
    const employerMap = new Map();
    let employersCreatedOrUpdated = 0;

    for (const empData of EMPLOYER_SEEDS) {
      const existing = await Employer.findOne({ email: empData.email });
      if (existing) {
        // Update company profile details safely without overwriting password
        Object.assign(existing, {
          name: empData.name,
          companyName: empData.companyName,
          companyWebsite: empData.companyWebsite,
          natureOfBusiness: empData.natureOfBusiness,
          description: empData.description,
          location: empData.location,
          officeLocation: empData.officeLocation,
          industry: empData.industry,
          isVerified: true,
          isApproved: "approved",
          isProfileComplete: true,
          profilePicture: empData.profilePicture,
        });
        await existing.save();
        employerMap.set(empData.email, existing);
      } else {
        const passwordHash = await bcrypt.hash("JobOne@Test2026", 10);
        const newEmp = await new Employer({
          ...empData,
          password: passwordHash,
        }).save();
        employerMap.set(empData.email, newEmp);
        accounts.push({ type: "Employer", email: empData.email, password: "JobOne@Test2026" });
      }
      employersCreatedOrUpdated++;
    }

    // 3. Duplicate-safe Upsert for 32 Realistic Job Postings
    let jobsCreatedOrUpdated = 0;
    const industryCounts = {};

    for (const jobData of JOB_SEEDS) {
      const employer = employerMap.get(jobData.employerEmail);
      if (!employer) {
        console.warn(`Employer not found for ${jobData.employerEmail}; skipping job ${jobData.title}`);
        continue;
      }

      const jobPayload = {
        title: jobData.title,
        industry: jobData.industry,
        subdomain: jobData.subdomain,
        jobSummary: jobData.jobSummary,
        keyResponsibilities: jobData.keyResponsibilities,
        jobFeatures: jobData.jobFeatures || ["", ""],
        jobType: jobData.jobType,
        workDaysPattern: jobData.workDaysPattern,
        skillsRequired: jobData.skillsRequired,
        location: jobData.location,
        pinCode: jobData.pinCode,
        salaryMin: jobData.salaryMin,
        salaryMax: jobData.salaryMax,
        salaryCurrency: "INR",
        salaryFrequency: jobData.salaryFrequency || "Month",
        incentives: jobData.incentives || [],
        screeningQuestions: jobData.screeningQuestions || [],
        requestedDocuments: jobData.requestedDocuments || [],
        mode: jobData.mode,
        noOfPeopleRequired: jobData.noOfPeopleRequired || 1,
        genderPreference: "No Preference",
        qualifications: jobData.qualifications || [],
        languages: jobData.languages || ["English", "Hindi"],
        shifts: [{ shiftName: "Standard Shift", startTime: "09:30 AM", endTime: "06:30 PM" }],
        isFlexibleShifts: false,
        postedBy: employer._id,
        postedByName: employer.name,
        postedByImage: employer.profilePicture || "",
        postedByCompany: employer.companyName,
        postedAt: jobData.postedAt || new Date(),
        status: jobData.status || "active",
      };

      // Duplicate detection key: title + employer
      const savedJob = await Job.findOneAndUpdate(
        { title: jobPayload.title, postedBy: employer._id },
        { $set: jobPayload },
        { new: true, upsert: true }
      );

      // Keep employer's createdJobs array synced
      if (!employer.createdJobs.some((id) => id.toString() === savedJob._id.toString())) {
        employer.createdJobs.push(savedJob._id);
        await employer.save();
      }

      jobsCreatedOrUpdated++;
      industryCounts[jobData.industry] = (industryCounts[jobData.industry] || 0) + 1;
    }

    // 4. Print Structured Execution Summary
    console.log("\n=================================");
    console.log("JobOne Development Seed Summary");
    console.log("=================================");
    console.log(`Employers created/updated: ${employersCreatedOrUpdated}`);
    console.log(`Jobs created/updated: ${jobsCreatedOrUpdated}`);
    console.log("\nIndustries Covered:");
    for (const [ind, count] of Object.entries(industryCounts)) {
      console.log(`  • ${ind}: ${count} jobs`);
    }

    if (accounts.length > 0) {
      console.log("\nNewly Generated Seed Accounts:");
      for (const account of accounts) {
        console.log(`  ${account.type}: ${account.email} | password: ${account.password}`);
      }
    }

    console.log("\nSeed completed successfully.");
    console.log("=================================\n");
  } catch (error) {
    console.error("Seed execution failed:", error);
    process.exit(1);
  } finally {
    await mongoose.disconnect();
    console.log("Database connection closed.");
  }
}

seedDatabase();
